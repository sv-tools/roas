#[test]
fn review_regressions() {
    // A component `$ref` with siblings is the intersection holder, not itself.
    let g = generate(
        &document(serde_json::json!({
            "Pet": {"type": "object", "properties": {"name": {"type": "string"}}},
            "Short": {"$ref": "#/components/schemas/Pet", "maxProperties": 3}
        })),
        &rust_config(""),
    )
    .unwrap();
    let code = &g.files[0].contents;
    assert!(code.contains("pub struct Short {"), "{code}");
    assert!(!code.contains("Short(pub Short)"), "{code}");

    // `union` is a keyword; backend-owned names do not collide with components.
    let g = generate(
        &document(serde_json::json!({
            "String": {"type": "object", "properties": {"union": {"type": "string"}}},
            "Serialize": {"type": "string"}
        })),
        &rust_config(""),
    )
    .unwrap();
    let code = &g.files[0].contents;
    assert!(code.contains("pub r#union: Option<String>,"), "{code}");
    assert!(code.contains("pub struct String2 {"), "{code}");
    assert!(code.contains("pub struct Serialize2("), "{code}");

    // `x-rust-attrs` goes through the ownership check: the serde key is dropped.
    let g = generate(
        &document(serde_json::json!({
            "Pet": {"type": "object", "properties": {"name": {"type": "string", "x-rust-attrs": ["#[serde(default)]", "#[doc(hidden)]"]}}}
        })),
        &rust_config("allow_codegen_extensions = true\n"),
    )
    .unwrap();
    let code = &g.files[0].contents;
    assert!(code.contains("#[doc(hidden)]"), "{code}");
    assert!(!code.contains("#[serde(default)]"), "{code}");
    assert!(g.diagnostics.iter().any(|d| matches!(
        d.kind,
        DiagnosticKind::IgnoredExtension { .. }
    ) && d.message.contains("default")));

    // An allOf branch with an unsupported keyword is not flattened.
    let g = generate(
        &document(serde_json::json!({
            "Both": {"allOf": [
                {"type": "object", "properties": {"a": {"type": "string"}}, "dependentRequired": {"a": ["b"]}},
                {"type": "object", "properties": {"b": {"type": "string"}}}
            ]}
        })),
        &rust_config(""),
    )
    .unwrap();
    assert!(
        g.diagnostics.iter().any(
            |d| matches!(&d.kind, DiagnosticKind::OpenComposition { keyword } if keyword == "allOf")
        ),
        "{:?}",
        g.diagnostics
    );
    assert!(g.diagnostics.iter().any(|d| matches!(&d.kind, DiagnosticKind::UnsupportedKeyword { keyword } if keyword == "dependentRequired")), "{:?}", g.diagnostics);

    // A string `const` is enforced by the type, as a one-value enum; a
    // non-string `const` is reported.
    let g = generate(
        &document(
            serde_json::json!({"Fixed": {"type": "object", "properties": {
                "kind": {"type": "string", "const": "fixed"},
                "n": {"type": "integer", "minimum": 0, "maximum": 9, "const": 1}
            }}}),
        ),
        &rust_config(""),
    )
    .unwrap();
    assert!(
        g.files[0].contents.contains("pub enum FixedKind {"),
        "{}",
        g.files[0].contents
    );
    let consts = g.diagnostics.iter().filter(|d| matches!(&d.kind, DiagnosticKind::UnsupportedKeyword { keyword } if keyword == "const")).count();
    assert_eq!(consts, 1, "{:?}", g.diagnostics);

    // `const` on a composition is reported, not dropped.
    let g = generate(
        &document(serde_json::json!({"One": {"allOf": [{"type": "integer", "minimum": 0, "maximum": 9}], "const": 1}})),
        &rust_config(""),
    )
    .unwrap();
    assert!(g.diagnostics.iter().any(|d| matches!(&d.kind, DiagnosticKind::UnsupportedKeyword { keyword } if keyword == "const")), "{:?}", g.diagnostics);

    // A helper module name is reserved against a configured rename.
    let g = generate(
        &document(pet()),
        &rust_config("[types.Pet]\nrename = \"double_option\"\n"),
    )
    .unwrap();
    assert!(
        g.files[0].contents.contains("pub struct double_option2 {"),
        "{}",
        g.files[0].contents
    );

    // A multi-line title stays inside the doc comment.
    let g = generate(
        &document(serde_json::json!({"Pet": {"title": "First\npub struct Injected;", "type": "object", "properties": {"a": {"type": "string"}}}})),
        &rust_config(""),
    )
    .unwrap();
    let code = &g.files[0].contents;
    assert!(code.contains("/// pub struct Injected;"), "{code}");
    assert!(
        !code.lines().any(|l| l.trim() == "pub struct Injected;"),
        "{code}"
    );

    // A nullable branch cannot be proven tagged.
    let g = generate(
        &document(serde_json::json!({
            "Cat": {"type": ["object", "null"], "required": ["petType"], "properties": {"petType": {"type": "string", "const": "Cat"}}},
            "Dog": {"type": "object", "required": ["petType"], "properties": {"petType": {"type": "string", "const": "Dog"}}},
            "Pet": {"oneOf": [{"$ref": "#/components/schemas/Cat"}, {"$ref": "#/components/schemas/Dog"}], "discriminator": {"propertyName": "petType"}}
        })),
        &rust_config(""),
    )
    .unwrap();
    assert!(
        g.files[0].contents.contains("pub struct Pet {"),
        "{}",
        g.files[0].contents
    );

    // Integer bounds beyond the mapped width still warn; bounds inside it do not.
    let lossy = |schema: serde_json::Value| {
        generate(
            &document(serde_json::json!({"N": schema})),
            &rust_config(""),
        )
        .unwrap()
        .diagnostics
        .iter()
        .any(|d| matches!(d.kind, DiagnosticKind::LossyNumber))
    };
    assert!(lossy(
        serde_json::json!({"type": "integer", "minimum": -1e30, "maximum": 1e30})
    ));
    assert!(lossy(
        serde_json::json!({"type": "integer", "format": "int32", "minimum": 0, "maximum": 5000000000u64})
    ));
    assert!(!lossy(
        serde_json::json!({"type": "integer", "minimum": 0, "maximum": 100})
    ));
    assert!(lossy(
        serde_json::json!({"type": "integer", "minimum": 0, "maximum": 9223372036854775808u64})
    ));
    assert!(!lossy(
        serde_json::json!({"type": "integer", "minimum": -9223372036854775808i64, "maximum": 9223372036854775807i64})
    ));
    assert!(!lossy(
        serde_json::json!({"type": "integer", "minimum": -1.5, "maximum": 9.2e18})
    ));
}

#[test]
fn third_review_regressions() {
    // A newline in a pattern stays inside the doc comment.
    let g = generate(
        &document(serde_json::json!({"Pet": {"type": "object", "properties": {"a": {"type": "string", "pattern": "a\nfn injected() {}"}}}})),
        &rust_config(""),
    )
    .unwrap();
    let code = &g.files[0].contents;
    assert!(
        !code
            .lines()
            .any(|l| l.trim_start().starts_with("fn injected")),
        "{code}"
    );
    assert!(
        code.contains(r"`pattern`: `a\nfn injected() {}`."),
        "{code}"
    );

    // Each member of a multi-type union is its own type.
    let g = generate(
        &document(serde_json::json!({"V": {"type": ["object", "string"], "properties": {"a": {"type": "string"}}, "maxLength": 3}})),
        &rust_config(""),
    )
    .unwrap();
    let code = &g.files[0].contents;
    assert!(code.contains("pub struct V {"), "{code}");
    assert!(code.contains("pub struct VObject {"), "{code}");
    assert!(code.contains("pub a: Option<String>,"), "{code}");
    assert!(
        code.contains("pub fn as_v_object(&self) -> Option<VObject>"),
        "{code}"
    );
    assert!(
        code.contains("pub fn as_v_string(&self) -> Option<String>"),
        "{code}"
    );
    assert!(
        g.diagnostics.iter().all(|d| !d.pointer.contains('~')),
        "{:?}",
        g.diagnostics
    );

    // A keyword that fits no member is reported.
    let g = generate(
        &document(serde_json::json!({"W": {"type": ["string", "integer"], "minimum": 0, "maximum": 9, "contains": {"type": "string"}}})),
        &rust_config(""),
    )
    .unwrap();
    assert!(g.diagnostics.iter().any(|d| matches!(&d.kind, DiagnosticKind::UnsupportedKeyword { keyword } if keyword == "contains") && d.pointer == "/components/schemas/W"), "{:?}", g.diagnostics);

    // Attributes on an alias are kept, through a transparent newtype.
    let components = serde_json::json!({
        "Pet": {"type": "object", "properties": {"a": {"type": "string"}}},
        "Animal": {"$ref": "#/components/schemas/Pet"}
    });
    let g = generate(
        &document(components.clone()),
        &rust_config("[types.Animal]\nattrs = ['#[doc(hidden)]']\n"),
    )
    .unwrap();
    let code = &g.files[0].contents;
    assert!(code.contains("#[doc(hidden)]"), "{code}");
    assert!(code.contains("pub struct Animal(pub Pet);"), "{code}");
    let g = generate(&document(components), &rust_config("")).unwrap();
    assert!(g.files[0].contents.contains("pub type Animal = Pet;"));

    // Composed holders have constructors as well as accessors.
    let g = generate(
        &document(serde_json::json!({
            "Pet": {"type": "object", "properties": {"a": {"type": "string"}}},
            "Strict": {"allOf": [{"$ref": "#/components/schemas/Pet"}, {"type": "object", "additionalProperties": false}]}
        })),
        &rust_config(""),
    )
    .unwrap();
    assert!(
        g.files[0]
            .contents
            .contains("pub fn from_pet(value: &Pet) -> Result<Self, serde_json::Error>"),
        "{}",
        g.files[0].contents
    );
}
