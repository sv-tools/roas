fn the_file_and_package_are_configurable_and_checked() {
    let Some(generation) = go(pet(), "[go]\nfile = \"pets\"\npackage = \"petstore\"\n") else {
        return;
    };
    let file = &generation.unwrap().files[0];
    assert_eq!(file.path, Path::new("pets.go"));
    assert!(file.contents.contains("\npackage petstore\n"));
    // The output is a package in the user's own module: no go.mod, so no
    // module path to set.
    assert!(
        ConfigFile::from_toml("[go]\nmodule_path = \"example.com/pets\"\n", Path::new("/"))
            .is_err()
    );
    // Rust-only settings do not stop a Go run.
    assert!(go(pet(), "[rust]\nedition = \"2027\"\n").unwrap().is_ok());
    for (toml, bad) in [
        ("[go]\npackage = \"type\"\n", "package"),
        ("[go]\npackage = \"Pets\"\n", "package"),
        ("[go]\npackage = \"init\"\n", "package"),
        ("[go]\npackage = \"documentation\"\n", "package"),
        ("[go]\npackage = \"main\"\n", "package"),
        ("[go]\nfile = \"pets_windows\"\n", "file"),
        ("[go]\nfile = \"pets_test\"\n", "file"),
        ("[go]\nfile = \"nul\"\n", "file"),
    ] {
        let error = ConfigFile::from_toml(&format!("target = \"go\"\n{toml}"), Path::new("/"))
            .unwrap()
            .build()
            .unwrap_err();
        match bad {
            "package" => assert!(
                matches!(error, ConfigError::InvalidPackage(_)),
                "{toml}: {error}"
            ),
            _ => assert!(
                matches!(error, ConfigError::InvalidGoFile(_)),
                "{toml}: {error}"
            ),
        }
    }
}

